create policy "admins_select_properties" on public.properties
for select to authenticated using (public.is_admin());

create policy "admins_update_properties" on public.properties
for update to authenticated using (public.is_admin()) with check (public.is_admin());

create policy "admins_read_admin_users" on public.admin_users
for select to authenticated using (public.is_admin());

create policy "admins_read_bookings" on public.bookings
for select to authenticated using (public.is_admin());

create policy "admins_manage_bookings" on public.bookings
for all to authenticated using (public.is_admin()) with check (public.is_admin());

create policy "admins_read_booking_events" on public.booking_events
for select to authenticated using (public.is_admin());

create policy "admins_add_booking_events" on public.booking_events
for insert to authenticated with check (public.is_admin());


create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_users a
    where a.user_id = auth.uid() and a.active = true
  );
$$;

create or replace function public.get_public_availability(
  p_property_slug text,
  p_from date,
  p_to date
)
returns table(date_from date, date_to date)
language sql
stable
security definer
set search_path = public
as $$
  select b.date_from, b.date_to
  from public.bookings b
  join public.properties p on p.id = b.property_id
  where p.slug = p_property_slug
    and p.active = true
    and b.status in ('booked','completed')
    and daterange(b.date_from, b.date_to + 1, '[)') && daterange(p_from, p_to + 1, '[)')
  order by b.date_from;
$$;

create or replace function public.get_public_property(p_property_slug text)
returns table(
  slug text,
  name text,
  description text,
  member_rate integer,
  non_member_rate integer,
  contact_email text
)
language sql
stable
security definer
set search_path = public
as $$
  select p.slug, p.name, p.description, p.member_rate, p.non_member_rate, p.contact_email
  from public.properties p
  where p.slug = p_property_slug and p.active = true;
$$;

